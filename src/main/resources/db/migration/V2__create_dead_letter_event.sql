-- Mensajes de RabbitMQ que terminaron en una DLQ (q.cmd.*.dlq).
-- Los llena DeadLetterAuditListener a partir de la cola q.audit.deadletter.

CREATE TABLE DEAD_LETTER_EVENT (
    ID              NUMBER(19)      NOT NULL,
    EVENT_ID        VARCHAR2(100),
    SOURCE_QUEUE    VARCHAR2(200)   NOT NULL,
    SOURCE_EXCHANGE VARCHAR2(200),
    ROUTING_KEY     VARCHAR2(200),
    REASON          VARCHAR2(50)    NOT NULL,
    ATTEMPTS        NUMBER(10)      NOT NULL,
    DEAD_AT         TIMESTAMP       NOT NULL,
    RECEIVED_AT     TIMESTAMP       NOT NULL,
    RAW_PAYLOAD     CLOB,
    CONSTRAINT PK_DEAD_LETTER_EVENT PRIMARY KEY (ID)
);

CREATE SEQUENCE DEAD_LETTER_EVENT_SEQ START WITH 1 INCREMENT BY 50 NOCACHE;

CREATE INDEX IX_DLE_SOURCE_QUEUE ON DEAD_LETTER_EVENT (SOURCE_QUEUE);
CREATE INDEX IX_DLE_EVENT_ID ON DEAD_LETTER_EVENT (EVENT_ID);
CREATE INDEX IX_DLE_DEAD_AT ON DEAD_LETTER_EVENT (DEAD_AT);